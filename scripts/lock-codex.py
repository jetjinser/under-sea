#!/usr/bin/env python3
"""Lock upstream Codex Cargo.lock registry crates and exact Git source archives."""
import argparse, concurrent.futures, hashlib, json, re, runpy, shutil, subprocess, tarfile, tomllib
from pathlib import Path
from urllib.parse import urlsplit
helpers = runpy.run_path(str(Path(__file__).with_name('lock-hermes.py')))
fetch, origin, scheme = helpers['fetch'], helpers['origin'], helpers['scheme']

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path)
    parser.add_argument('source', type=Path)
    parser.add_argument('--cache', type=Path, default=Path('/tmp/under-sea-codex-lock/inputs'))
    parser.add_argument('--output', type=Path, default=Path('under-sea/packages/codex-lock.scm'))
    args = parser.parse_args(); args.cache.mkdir(parents=True, exist_ok=True)
    lock_path = args.source / 'codex-rs/Cargo.lock'
    with tarfile.open(args.archive) as archive:
        root = archive.getmembers()[0].name.split('/')[0]
        for name in ('Cargo.lock', 'Cargo.toml'):
            if archive.extractfile(root + '/codex-rs/' + name).read() != (args.source/'codex-rs'/name).read_bytes():
                raise ValueError('Archive and source disagree: ' + name)
    version = tomllib.loads((args.source/'codex-rs/Cargo.toml').read_text())['workspace']['package']['version']
    packages = tomllib.loads(lock_path.read_text())['package']
    # These crates bundle executables. Use Guix's source-built protoc instead.
    crates = sorted((p['name'], p['version'], p['checksum']) for p in packages
                    if p.get('source','').startswith('registry+')
                    and not p['name'].startswith('protoc-bin-vendored'))
    git_sources = sorted({p['source'] for p in packages if p.get('source','').startswith('git+')})
    print(f'{len(crates)} registry sources; {len(git_sources)} Git repositories', flush=True)
    def crate(item):
        name, ver, sha = item; filename = f'{name}-{ver}.crate'
        old = Path('/tmp/under-sea-hermes-lock/inputs') / filename
        dest = args.cache / filename
        if old.exists() and hashlib.sha256(old.read_bytes()).hexdigest() == sha and not dest.exists(): shutil.copyfile(old,dest)
        url = f'https://static.crates.io/crates/{name}/{filename}'
        size = None
        partial = dest.with_suffix(dest.suffix + '.part')
        if not dest.exists() and partial.exists() and partial.stat().st_size > 2*1024*1024:
            headers = subprocess.check_output(['curl','-fLsSI','--retry','3',
                '--connect-timeout','20','--max-time','90',url],text=True)
            lengths = re.findall(r'^content-length: (\d+)',headers,re.I|re.M)
            if lengths: size = int(lengths[-1])
        return fetch((url, filename, sha, size), args.cache,
                     'https://static.crates.io/crates')
    with concurrent.futures.ThreadPoolExecutor(max_workers=20) as pool: sources = list(pool.map(crate, crates))
    git_entries = []
    for source in git_sources:
        parsed = urlsplit(source.removeprefix('git+')); rev = parsed.fragment
        assert parsed.hostname == 'github.com' and len(rev) == 40
        repo = parsed.path.removesuffix('.git').strip('/')
        url = f'https://codeload.github.com/{repo}/tar.gz/{rev}'
        name = repo.replace('/','-') + '-' + rev + '.tar.gz'; dest = args.cache/name
        if not dest.exists():
            temporary = dest.with_suffix('.download')
            subprocess.run(['curl','-fLsS','--retry','5','--retry-all-errors',
                            '--connect-timeout','30','--max-time','1800',
                            url,'-o',str(temporary)],check=True)
            with tarfile.open(temporary) as archive: archive.getmembers()
            temporary.replace(dest)
        git_entries.append((source, url, name, dest))
    source_origin = origin(f'https://codeload.github.com/openai/codex/tar.gz/refs/tags/rust-v{version}',args.archive.name,args.archive)
    shutil.copyfile(args.archive,args.cache/args.archive.name)
    lines = [';;; Generated by scripts/lock-codex.py; exact upstream sources.', '(define-module (under-sea packages codex-lock)', '  #:use-module (guix packages)', '  #:use-module (guix download)', '  #:use-module (guix base16))', f'(define-public %codex-version {scheme(version)})', f'(define-public %codex-source {source_origin})', '(define-public %codex-crate-sources (list']
    for (name,ver,sha),(url,filename,path) in zip(crates,sources): lines.append(f'  (list {scheme(name+"-"+ver)} {scheme(sha)} {origin(url,filename,path)})')
    lines += ['))', '(define-public %codex-git-sources (list']
    for source,url,name,path in git_entries: lines.append(f'  (list {scheme(source)} {origin(url,name,path)})')
    lines += ['))','']
    temporary=args.output.with_suffix(args.output.suffix+'.tmp')
    temporary.write_text('\n'.join(lines)); temporary.replace(args.output)
    print(f'Wrote {args.output}',flush=True)
if __name__ == '__main__': main()
