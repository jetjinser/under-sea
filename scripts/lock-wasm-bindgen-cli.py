"""Authenticate wasm-bindgen CLI's complete source workspace and locked inputs."""
import argparse
import concurrent.futures
import hashlib
import json
from pathlib import Path
import runpy
import subprocess
import tarfile
import tomllib
from urllib.parse import urlsplit

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('archive',type=Path)
parser.add_argument('source',type=Path)
args=parser.parse_args()
inventory=json.loads(Path('planning/hermes-wasm-bindgen-cli-source.json').read_text())
if hashlib.sha256(args.archive.read_bytes()).hexdigest()!=inventory['sha256']:
    raise ValueError('Source archive differs from reviewed identity')
with tarfile.open(args.archive) as tar:
    for relative in ('Cargo.toml','crates/cli/Cargo.toml'):
        if tar.extractfile('wasm-bindgen-0.2.129/'+relative).read()!=(args.source/relative).read_bytes():
            raise ValueError('Changed source manifest: '+relative)
lock=args.source/'Cargo.lock'
if lock.read_bytes()!=Path('planning/wasm-bindgen-cli-Cargo.lock').read_bytes():
    raise ValueError('Changed reviewed dependency lock')
packages=tomllib.loads(lock.read_text())['package']
registry=sorted((p['name'],p['version'],p['checksum']) for p in packages if p.get('source','').startswith('registry+'))
gits=sorted({p['source'] for p in packages if p.get('source','').startswith('git+')})
if gits!=inventory['git_origins']:
    raise ValueError('Changed Git origin list')
for p in packages:
    if p.get('source','').startswith('registry+') and p['source']!='registry+https://github.com/rust-lang/crates.io-index':
        raise ValueError('Unreviewed registry')
helpers=runpy.run_path(str(Path(__file__).with_name('lock-hermes.py')))
fetch,origin,scheme=[helpers[k] for k in ('fetch','origin','scheme')]
cache=Path('/tmp/under-sea-wasm-bindgen-cli/inputs');cache.mkdir(parents=True,exist_ok=True)
def download(item):
    name,version,checksum=item;filename=name+'-'+version+'.crate'
    return fetch(('https://static.crates.io/crates/'+name+'/'+filename,filename,checksum,None),cache)
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    inputs=list(pool.map(download,registry))
lines=[';;; Generated by scripts/lock-wasm-bindgen-cli.py.',
 '(define-module (under-sea packages wasm-bindgen-cli-lock)',
 ' #:use-module (guix packages) #:use-module (guix download) #:use-module (guix base16))',
 '(define-public %wasm-bindgen-cli-source '+origin(inventory['uri'],args.archive.name,args.archive)+')',
 '(define-public %wasm-bindgen-cli-crate-sources (list']
for (name,version,checksum),(url,filename,path) in zip(registry,inputs):
    lines.append('(list '+scheme(name+'-'+version)+' '+scheme(checksum)+' '+origin(url,filename,path)+')')
lines.extend(['))','(define-public %wasm-bindgen-cli-git-sources (list'])
for identity in gits:
    parsed=urlsplit(identity.removeprefix('git+'))
    if parsed.hostname!='github.com' or len(parsed.fragment)!=40:
        raise ValueError('Unreviewed Git host or revision')
    repo=parsed.path.strip('/').removesuffix('.git')
    url='https://codeload.github.com/'+repo+'/tar.gz/'+parsed.fragment
    filename=repo.replace('/','-')+'-'+parsed.fragment+'.tar.gz'
    archive=cache/filename
    if not archive.exists():
        temporary=archive.with_suffix('.download')
        subprocess.run(['curl','-fLsS','--retry','4',url,'-o',str(temporary)],check=True)
        with tarfile.open(temporary) as tar:tar.getmembers()
        temporary.replace(archive)
    lines.append('(list '+scheme(identity)+' '+origin(url,filename,archive)+')')
lines.extend(['))',''])
output=Path('under-sea/packages/wasm-bindgen-cli-lock.scm')
temporary=output.with_suffix('.scm.tmp');temporary.write_text('\n'.join(lines));temporary.replace(output)
print(f'Locked {len(registry)} registry archives and {len(gits)} exact Git archives',flush=True)
