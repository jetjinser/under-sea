#!/usr/bin/env python3
"""Lock Loro's exact crates.io sources for the offline Python build."""
import argparse
import hashlib
import json
import tomllib
import urllib.request
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--version", required=True)
    ap.add_argument("--source", type=Path, required=True,
                    help="extracted Loro source tree containing Cargo.lock")
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--cache", type=Path,
                    default=Path.home() / ".cache" / "loro-crates")
    ap.add_argument("--source-url", required=True)
    ap.add_argument("--source-sha256", required=True,
                    help="nix-base32 sha256 of the PyPI sdist")
    args = ap.parse_args()

    cache = args.cache
    cache.mkdir(parents=True, exist_ok=True)
    lock = tomllib.loads((args.source / "Cargo.lock").read_text())
    crates = sorted((p["name"], p["version"], p.get("checksum", ""))
                    for p in lock["package"]
                    if p.get("source", "").startswith("registry+"))
    print(f"Locking {len(crates)} registry crates", flush=True)

    sources = []
    for name, ver, checksum in crates:
        filename = f"{name}-{ver}.crate"
        dest = cache / filename
        if dest.exists() and hashlib.sha256(dest.read_bytes()).hexdigest() == checksum:
            sources.append((name, ver, checksum, dest))
            continue
        url = f"https://static.crates.io/crates/{name}/{filename}"
        print(f"  downloading {filename}...", flush=True)
        for attempt in range(3):
            try:
                urllib.request.urlretrieve(url, dest)
                break
            except Exception as exc:  # noqa: BLE001
                print(f"  retry {attempt + 1}: {exc}", flush=True)
        if not dest.is_file():
            raise SystemExit(f"could not download {filename}")
        got = hashlib.sha256(dest.read_bytes()).hexdigest()
        if got != checksum:
            raise SystemExit(f"checksum mismatch: {filename}")
        sources.append((name, ver, checksum, dest))

    lines = [
        ";;; Generated by scripts/lock-loro.py; exact crates.io sources.",
        "(define-module (under-sea packages loro-lock)",
        "  #:use-module (guix packages)",
        "  #:use-module (guix download)",
        "  #:use-module (guix base32)",
        "  #:use-module (guix base16)",
        "  #:export (%loro-version %loro-source %loro-crate-sources))",
        "",
        f"(define %loro-version {json.dumps(args.version)})",
        "(define %loro-source",
        "  (origin (method url-fetch)",
        f'          (uri {json.dumps(args.source_url)})',
        f'          (file-name "loro-{args.version}.tar.gz")',
        f'          (sha256 (base32 {json.dumps(args.source_sha256)}))))',
        "(define %loro-crate-sources (list",
    ]
    for name, ver, checksum, _dest in sources:
        url = f"https://static.crates.io/crates/{name}/{name}-{ver}.crate"
        lines.append(
            "  (list " + json.dumps(name + "-" + ver) + " "
            + json.dumps(checksum)
            + " (origin (method url-fetch) (uri " + json.dumps(url) + ")"
            + " (sha256 (base16-string->bytevector "
            + json.dumps(checksum) + "))))")
    lines.append("))")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"Wrote {args.output}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
