#!/usr/bin/env python3
"""Lock agent-browser's exact registry sources for offline Linux builds."""
import argparse
import concurrent.futures
import hashlib
from pathlib import Path
import runpy
import shutil
import tarfile
import tomllib

helpers = runpy.run_path(str(Path(__file__).with_name('lock-hermes.py')))
fetch, origin, scheme = (helpers[key] for key in ('fetch', 'origin', 'scheme'))
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('archive', type=Path)
parser.add_argument('source', type=Path)
parser.add_argument('--cache', type=Path, default=Path('/tmp/under-sea-agent-browser-sources/inputs'))
parser.add_argument('--output', type=Path, default=Path('modules/under-sea/packages/agent-browser-lock.scm'))
args = parser.parse_args()
args.cache.mkdir(parents=True, exist_ok=True)
with tarfile.open(args.archive) as archive:
    root = archive.getmembers()[0].name.split('/')[0]
    for relative in ('cli/Cargo.lock', 'cli/Cargo.toml', 'pnpm-lock.yaml', 'package.json'):
        if archive.extractfile(root + '/' + relative).read() != (args.source / relative).read_bytes():
            raise ValueError('Source/archive mismatch: ' + relative)
manifest = tomllib.loads((args.source / 'cli/Cargo.toml').read_text())
version = manifest['package']['version']
packages = tomllib.loads((args.source / 'cli/Cargo.lock').read_text())['package']
if any(package.get('source', '').startswith('git+') for package in packages):
    raise ValueError('Unreviewed Git source in agent-browser lock')
crates = sorted((package['name'], package['version'], package['checksum'])
                for package in packages if package.get('source', '').startswith('registry+'))

def download(item):
    name, version, checksum = item
    filename = name + '-' + version + '.crate'
    target = args.cache / filename
    # Reuse only exact source bytes from the dedicated, previously reviewed
    # caches. Their Cargo checksum is authoritative; no wheel/artifact reuse.
    for cache in ('/tmp/under-sea-hermes-full-audio-lock', '/tmp/under-sea-hermes-lock/inputs',
                  '/tmp/under-sea-codex-lock/inputs'):
        candidate = Path(cache) / filename
        if not target.exists() and candidate.is_file():
            if hashlib.sha256(candidate.read_bytes()).hexdigest() == checksum:
                shutil.copyfile(candidate, target)
                break
    url = 'https://static.crates.io/crates/' + name + '/' + filename
    return fetch((url, filename, checksum, None), args.cache)

print(f'Locking {len(crates)} registry sources for agent-browser {version}', flush=True)
with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
    sources = list(pool.map(download, crates))
source_url = 'https://codeload.github.com/vercel-labs/agent-browser/tar.gz/refs/tags/v' + version
lines = [';;; Generated by scripts/lock-agent-browser.py; exact source inputs.',
         '(define-module (under-sea packages agent-browser-lock)',
         '  #:use-module (guix packages)', '  #:use-module (guix download)',
         '  #:use-module (guix base16))',
         '(define-public %agent-browser-version ' + scheme(version) + ')',
         '(define-public %agent-browser-source ' + origin(source_url, args.archive.name, args.archive) + ')',
         '(define-public %agent-browser-crate-sources (list']
for (name, version, checksum), (url, filename, path) in zip(crates, sources):
    lines.append('  (list ' + scheme(name + '-' + version) + ' ' + scheme(checksum) +
                 ' ' + origin(url, filename, path) + ')')
lines.extend(['))', ''])
temporary = args.output.with_suffix(args.output.suffix + '.tmp')
temporary.write_text('\n'.join(lines))
temporary.replace(args.output)
print('Wrote ' + str(args.output), flush=True)
