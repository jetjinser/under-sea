#!/usr/bin/env python3
"""Lock next-native's exact registry sources for offline Linux builds."""
import argparse
import concurrent.futures
import hashlib
import json
import re
import subprocess
from urllib.parse import urlsplit
from pathlib import Path
import shutil
import tarfile
import tomllib

from lock_lib import fetch, origin, scheme
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('archive', type=Path)
parser.add_argument('source', type=Path)
parser.add_argument('--cache', type=Path, default=Path('/tmp/under-sea-next-native-sources/inputs'))
parser.add_argument('--output', type=Path, default=Path('modules/under-sea/packages/next-native-lock.scm'))
parser.add_argument('--module', default='next-native-lock')
parser.add_argument('--lock-relative', type=Path, default=Path('Cargo.lock'),
                    help='Authored independent Cargo lock, relative to Next source root')
args = parser.parse_args()
if not re.fullmatch(r'[a-z0-9-]+', args.module):
    raise ValueError('Invalid generated Scheme module name')
if args.lock_relative.is_absolute() or '..' in args.lock_relative.parts or args.lock_relative.name != 'Cargo.lock':
    raise ValueError('Expected safe authored Cargo.lock relative path')
args.cache.mkdir(parents=True, exist_ok=True)
with tarfile.open(args.archive) as archive:
    root = archive.getmembers()[0].name.split('/')[0]
    for relative in sorted(set(('Cargo.lock', 'Cargo.toml', 'pnpm-lock.yaml', 'packages/next/package.json',
                               str(args.lock_relative), str(args.lock_relative.with_name('Cargo.toml'))))):
        if archive.extractfile(root + '/' + relative).read() != (args.source / relative).read_bytes():
            raise ValueError('Source/archive mismatch: ' + relative)
version = json.loads((args.source/'packages/next/package.json').read_text())['version']
packages = tomllib.loads((args.source / args.lock_relative).read_text())['package']
git_sources = sorted({package['source'] for package in packages if package.get('source','').startswith('git+')})
crates = sorted((package['name'], package['version'], package['checksum'])
                for package in packages if package.get('source', '').startswith('registry+'))

def download(item):
    name, version, checksum = item
    filename = name + '-' + version + '.crate'
    target = args.cache / filename
    # Reuse only exact source bytes from the dedicated, previously reviewed
    # caches. Their Cargo checksum is authoritative; no wheel/artifact reuse.
    for cache in ('/tmp/under-sea-hermes-full-audio-lock', '/tmp/under-sea-hermes-lock/inputs',
                  '/tmp/under-sea-codex-lock/inputs', '/tmp/under-sea-next-native-sources/inputs',
                  '/tmp/under-sea-next-1608-native/inputs'):
        candidate = Path(cache) / filename
        if not target.exists() and candidate.is_file():
            if hashlib.sha256(candidate.read_bytes()).hexdigest() == checksum:
                shutil.copyfile(candidate, target)
                break
    url = 'https://static.crates.io/crates/' + name + '/' + filename
    return fetch((url, filename, checksum, None), args.cache)

print(f'Locking {len(crates)} registry sources for next-native {version}', flush=True)
with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
    sources = list(pool.map(download, crates))
source_url = 'https://codeload.github.com/vercel/next.js/tar.gz/refs/tags/v' + version
lines = [';;; Generated by scripts/lock-next-native.py; exact source inputs.',
         f'(define-module (under-sea packages {args.module})',
         '  #:use-module (guix packages)', '  #:use-module (guix download)',
         '  #:use-module (guix base16))',
         '(define-public %next-native-version ' + scheme(version) + ')',
         '(define-public %next-native-source ' + origin(source_url, args.archive.name, args.archive) + ')',
         '(define-public %next-native-crate-sources (list']
for (name, version, checksum), (url, filename, path) in zip(crates, sources):
    lines.append('  (list ' + scheme(name + '-' + version) + ' ' + scheme(checksum) +
                 ' ' + origin(url, filename, path) + ')')
lines.extend(['))', '(define-public %next-native-git-sources (list'])
for identity in git_sources:
    parsed=urlsplit(identity.removeprefix('git+'))
    if parsed.hostname!='github.com' or not re.fullmatch(r'[0-9a-f]{40}',parsed.fragment):
        raise ValueError('Unreviewed Git origin: '+identity)
    repository=parsed.path.strip('/').removesuffix('.git')
    url='https://codeload.github.com/'+repository+'/tar.gz/'+parsed.fragment
    filename=repository.replace('/','-')+'-'+parsed.fragment+'.tar.gz'
    target=args.cache/filename
    if not target.is_file():
        temporary=target.with_suffix('.download')
        subprocess.run(['curl','-fLsS','--retry','4','--connect-timeout','30',
                        '--max-time','300',url,'-o',str(temporary)],check=True)
        with tarfile.open(temporary) as archive:
            archive.getmembers()
        temporary.replace(target)
    lines.append('  (list '+scheme(identity)+' '+origin(url,filename,target)+')')
lines.extend(['))',''])
temporary = args.output.with_suffix(args.output.suffix + '.tmp')
temporary.write_text('\n'.join(lines))
temporary.replace(args.output)
print('Wrote ' + str(args.output), flush=True)
