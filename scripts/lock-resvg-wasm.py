"""Lock resvg's registry and exact Git source archives for offline builds."""
import argparse
import concurrent.futures
from pathlib import Path
import subprocess
import tarfile
import tomllib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('archive', type=Path)
parser.add_argument('source', type=Path)
args = parser.parse_args()
from lock_lib import fetch, origin, scheme
commit = '30ac8d830d44802df7e967569c92edabbbcec017'
with tarfile.open(args.archive) as archive:
    for relative in ('Cargo.toml', 'package.json', 'build.rs'):
        if archive.extractfile('resvg-js-'+commit+'/'+relative).read() != (args.source/relative).read_bytes():
            raise ValueError('Original source changed: '+relative)
lock = args.source/'Cargo.lock'
if lock.read_bytes() != Path('planning/resvg-wasm-Cargo.lock').read_bytes():
    raise ValueError('Reviewed Cargo lock differs')
packages = tomllib.loads(lock.read_text())['package']
registry = sorted((p['name'], p['version'], p['checksum']) for p in packages
                  if p.get('source','').startswith('registry+'))
git_identity = 'git+https://github.com/zimond/resvg?rev=6201182c#6201182cc109d45eb3596e81dede60783592db90'
for package in packages:
    source = package.get('source')
    if source is None and package['name'] != 'resvg-js':
        raise ValueError('Unexpected path package')
    if source and source not in ('registry+https://github.com/rust-lang/crates.io-index', git_identity):
        raise ValueError('Unreviewed source: '+source)
cache = Path('/tmp/under-sea-resvg-wasm/inputs')
cache.mkdir(parents=True, exist_ok=True)
def download(item):
    name, version, checksum = item
    filename = name+'-'+version+'.crate'
    return fetch(('https://static.crates.io/crates/'+name+'/'+filename,
                  filename, checksum, None), cache)
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    inputs = list(pool.map(download, registry))
git_commit = git_identity.split('#')[1]
git_url = 'https://codeload.github.com/zimond/resvg/tar.gz/'+git_commit
git_archive = cache/('resvg-'+git_commit+'.tar.gz')
if not git_archive.exists():
    temporary = git_archive.with_suffix('.download')
    subprocess.run(['curl','-fLsS','--retry','4',git_url,'-o',str(temporary)],check=True)
    with tarfile.open(temporary) as tar:
        if tar.getmembers()[0].name.rstrip('/') != 'resvg-'+git_commit:
            raise ValueError('Unexpected Git archive root')
    temporary.replace(git_archive)
lines = [';;; Generated by scripts/lock-resvg-wasm.py.',
         '(define-module (under-sea packages resvg-wasm-lock)',
         ' #:use-module (guix packages) #:use-module (guix download)',
         ' #:use-module (guix base16))',
         '(define-public %resvg-wasm-source '+origin(
             'https://codeload.github.com/yisibl/resvg-js/tar.gz/'+commit,
             args.archive.name,args.archive)+')',
         '(define-public %resvg-wasm-git-source '+origin(git_url,git_archive.name,git_archive)+')',
         '(define-public %resvg-wasm-crate-sources (list']
for (name,version,checksum),(url,filename,path) in zip(registry,inputs):
    lines.append('(list '+scheme(name+'-'+version)+' '+scheme(checksum)+' '+origin(url,filename,path)+')')
lines.extend(['))',''])
output=Path('modules/under-sea/packages/resvg-wasm-lock.scm')
temporary=output.with_suffix('.scm.tmp')
temporary.write_text('\n'.join(lines));temporary.replace(output)
print('Locked '+str(len(registry))+' registry archives and exact resvg Git source',flush=True)
