"""Authenticate source-map-mappings sources and fix its newly resolved inputs."""
import argparse
import concurrent.futures
import hashlib
import json
from pathlib import Path
import runpy
import tarfile
import tomllib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('archive', type=Path)
parser.add_argument('source', type=Path)
parser.add_argument('--cache', type=Path,
                    default=Path('/tmp/under-sea-source-map-wasm/inputs'))
args = parser.parse_args()
helpers = runpy.run_path(str(Path(__file__).with_name('lock-hermes.py')))
fetch, origin, scheme = [helpers[k] for k in ('fetch', 'origin', 'scheme')]
commit = '197660faf3dd1167c643797a5ed62cb687482c54'
with tarfile.open(args.archive) as archive:
    root = 'source-map-mappings-' + commit
    for relative in ('Cargo.toml', 'source-map-mappings-wasm-api/Cargo.toml'):
        if archive.extractfile(root + '/' + relative).read() != (args.source / relative).read_bytes():
            raise ValueError('Original source manifest changed: ' + relative)
    if tomllib.loads(archive.extractfile(root+'/Cargo.toml').read().decode())['package']['version'] != '0.5.0':
        raise ValueError('Unexpected implementation version')
lock = args.source / 'source-map-mappings-wasm-api/Cargo.lock'
packages = tomllib.loads(lock.read_text())['package']
crates = []
for package in packages:
    source = package.get('source')
    if source is None:
        if package['name'] not in ('source-map-mappings', 'source-map-mappings-wasm-api'):
            raise ValueError('Unexpected path package')
        continue
    if source != 'registry+https://github.com/rust-lang/crates.io-index':
        raise ValueError('Unreviewed dependency origin: ' + source)
    crates.append((package['name'], package['version'], package['checksum']))
crates.sort()
args.cache.mkdir(parents=True, exist_ok=True)
def download(item):
    name, version, checksum = item
    filename = name + '-' + version + '.crate'
    url = 'https://static.crates.io/crates/' + name + '/' + filename
    return fetch((url, filename, checksum, None), args.cache)
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    inputs = list(pool.map(download, crates))
destination = Path('planning/source-map-wasm-Cargo.lock')
destination.write_bytes(lock.read_bytes())
lines = [';;; Generated by scripts/lock-source-map-wasm.py.',
         '(define-module (under-sea packages source-map-wasm-lock)',
         ' #:use-module (guix packages) #:use-module (guix download)',
         ' #:use-module (guix base16))',
         '(define-public %source-map-wasm-source ' + origin(
             'https://codeload.github.com/fitzgen/source-map-mappings/tar.gz/'+commit,
             args.archive.name, args.archive) + ')',
         '(define-public %source-map-wasm-crate-sources (list']
for (name, version, checksum), (url, filename, path) in zip(crates, inputs):
    lines.append('(list '+scheme(name+'-'+version)+' '+scheme(checksum)+' '+origin(url, filename, path)+')')
lines.extend(['))', ''])
output = Path('modules/under-sea/packages/source-map-wasm-lock.scm')
temporary = output.with_suffix('.scm.tmp')
temporary.write_text('\n'.join(lines))
temporary.replace(output)
print(f'Authenticated and locked {len(crates)} source archives; lock SHA256 '
      + hashlib.sha256(lock.read_bytes()).hexdigest(), flush=True)
