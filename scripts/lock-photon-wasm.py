"""Lock photon's registry crate archives for an offline wasm build."""
import argparse
import concurrent.futures
import hashlib
from pathlib import Path
import runpy
import tomllib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('archive', type=Path)
parser.add_argument('source', type=Path)
args = parser.parse_args()
helpers = runpy.run_path(str(Path(__file__).with_name('lock-hermes.py')))
fetch, origin, scheme = [helpers[k] for k in ('fetch', 'origin', 'scheme')]
commit = 'e913bc48cf9609f149d3dbabbc94b43d337fc6a4'
lock = args.source / 'Cargo.lock'
if hashlib.sha256(lock.read_bytes()).hexdigest() != \
        hashlib.sha256(Path('planning/photon-wasm-Cargo.lock').read_bytes()).hexdigest():
    raise ValueError('Reviewed Cargo lock differs')
packages = tomllib.loads(lock.read_text())['package']
registry = sorted((p['name'], p['version'], p['checksum']) for p in packages
                  if p.get('source', '').startswith('registry+'))
for package in packages:
    source = package.get('source')
    if source is None:
        continue
    if source != 'registry+https://github.com/rust-lang/crates.io-index':
        raise ValueError('Unreviewed source: ' + source)
cache = Path('/tmp/under-sea-photon-wasm/inputs')
cache.mkdir(parents=True, exist_ok=True)


def download(item):
    name, version, checksum = item
    filename = name + '-' + version + '.crate'
    return fetch(('https://static.crates.io/crates/' + name + '/' + filename,
                  filename, checksum, None), cache)


with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    inputs = list(pool.map(download, registry))
lines = [';;; Generated by scripts/lock-photon-wasm.py.',
         '(define-module (under-sea packages photon-wasm-lock)',
         ' #:use-module (guix packages) #:use-module (guix download)',
         ' #:use-module (guix base16))',
         '(define-public %photon-wasm-source ' + origin(
             'https://codeload.github.com/silvia-odwyer/photon/tar.gz/' + commit,
             'photon-' + commit + '.tar.gz', args.archive) + ')',
         '(define-public %photon-wasm-crate-sources (list']
for (name, version, checksum), (url, filename, path) in zip(registry, inputs):
    lines.append('(list ' + scheme(name + '-' + version) + ' ' + scheme(checksum)
                 + ' ' + origin(url, filename, path) + ')')
lines.extend(['))', ''])
output = Path('modules/under-sea/packages/photon-wasm-lock.scm')
temporary = output.with_suffix('.scm.tmp')
temporary.write_text('\n'.join(lines))
temporary.replace(output)
print('Locked ' + str(len(registry)) + ' registry archives', flush=True)
