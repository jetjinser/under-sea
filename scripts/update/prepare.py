#!/usr/bin/env python3
"""Prepare a package pin update without running package managers.

This is the L2 prepare step: resolve the upstream artifact, hash it, and render
a generated *-pin.scm module.  Lock regeneration is deliberately a separate
adapter step (L3); this command never runs bun/cargo/go or edits a recipe.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run  # noqa: E402

ROOT = run.ROOT


def fetch(url, dest, timeout=600):
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.is_file() and dest.stat().st_size > 0:
        return dest
    tmp = dest.with_suffix(dest.suffix + ".part")
    subprocess.run(
        ["curl", "-fsSL", "--retry", "3", "--retry-delay", "2",
         "--max-time", str(timeout), "-o", str(tmp), url],
        check=True)
    tmp.rename(dest)
    return dest


def sha256_hex(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def guix_hash(path, fmt):
    flag = "base16" if fmt == "base16" else "nix-base32"
    return subprocess.check_output(
        ["guix", "hash", "-H", "sha256", "-f", flag, str(path)],
        text=True).strip()


def pypi_sdist(project, timeout=60):
    url = f"https://pypi.org/pypi/{project}/json"
    request = urllib.request.Request(
        url, headers={"User-Agent": "under-sea-update-prepare"})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        data = json.load(response)
    version = data["info"]["version"]
    for entry in data["urls"]:
        if entry.get("packagetype") == "sdist":
            return version, entry["url"]
    raise SystemExit(f"pypi: {project} has no sdist")


def render_pin(pkg, version, url, file_name, digest):
    module = pkg["pin_module"]
    version_symbol = pkg["version_symbol"]
    source_symbol = pkg["source_symbol"]
    fmt = pkg["hash_format"]
    hash_ctor = "base16-string->bytevector" if fmt == "base16" else "base32"
    import_name = "base16" if fmt == "base16" else "base32"
    return f''';;; Generated by scripts/update/prepare.py; do not edit.
(define-module (under-sea packages {module})
  #:use-module (guix packages)
  #:use-module (guix download)
  #:use-module (guix {import_name})
  #:export ({version_symbol} {source_symbol}))

(define-public {version_symbol} "{version}")

(define-public {source_symbol}
  (origin
    (method url-fetch)
    (uri "{url}")
    (file-name "{file_name}")
    (sha256
     ({hash_ctor} "{digest}"))))
'''


def render_git_pin(pkg, commit, digest):
    """Render a source-derived Guix git-fetch pin for a branch head."""
    module = pkg["pin_module"]
    version_symbol = pkg["version_symbol"]
    commit_symbol = pkg["commit_symbol"]
    source_symbol = pkg["source_symbol"]
    upstream = pkg["upstream"]
    version = upstream.get("version_prefix", "") + commit[:upstream.get(
        "version_length", 7)]
    return f''';;; Generated by scripts/update/prepare.py; do not edit.
(define-module (under-sea packages {module})
  #:use-module (guix packages)
  #:use-module (guix git-download)
  #:use-module (guix base32)
  #:export ({version_symbol} {commit_symbol} {source_symbol}))

(define-public {version_symbol} "{version}")
(define-public {commit_symbol} "{commit}")
(define-public {source_symbol}
  (origin
    (method git-fetch)
    (uri (git-reference
          (url "https://github.com/{upstream['repo']}")
          (commit {commit_symbol})))
    (file-name (git-file-name "{pkg['package']}" {version_symbol}))
    (sha256
     (base32 "{digest}"))))
'''


def git_commit_source(pkg, commit, workdir):
    """Fetch a branch commit and calculate its Guix NAR hash."""
    upstream = pkg["upstream"]
    checkout = workdir / "source"
    subprocess.run(["git", "clone", "--no-checkout",
                    f"https://github.com/{upstream['repo']}.git",
                    str(checkout)], check=True)
    subprocess.run(["git", "-C", str(checkout), "checkout", "--detach",
                    commit], check=True)
    actual = subprocess.check_output(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True).strip()
    if actual != commit:
        raise SystemExit(f"checked out {actual}, expected {commit}")
    digest = subprocess.check_output(
        ["guix", "hash", "--serializer=nar", "--exclude-vcs",
         "-H", "sha256", "-f", "nix-base32", str(checkout)], text=True).strip()
    return digest


def reject_dependent_pin_only_update(pkg):
    if pkg.get("adapter") == "dependent":
        raise ValueError(
            "dependent artifacts require their parent or a package-specific "
            "lock updater; refusing a pin-only rewrite")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--package", required=True)
    ap.add_argument("--version", help="target version (default: detected latest)")
    ap.add_argument("--commit", help="target full git commit for git-commit sources")
    ap.add_argument("--tag", help="GitHub tag (default: manifest tag_template)")
    ap.add_argument("--workdir", type=Path, default=None)
    ap.add_argument("--apply", action="store_true",
                    help="write the pin into the repository")
    ap.add_argument("--verify", action="store_true",
                    help="build the package after applying the pin")
    ap.add_argument("--manifest", type=Path, default=run.DEFAULT_MANIFEST)
    args = ap.parse_args()

    data = run.load_manifest(args.manifest)
    pkg = data["packages"].get(args.package)
    if not pkg:
        raise SystemExit(f"unknown package: {args.package}")
    try:
        reject_dependent_pin_only_update(pkg)
    except ValueError as error:
        raise SystemExit(f"{args.package}: {error}") from error
    if pkg.get("submodule_gate"):
        subprocess.run(
            [sys.executable, str(ROOT / pkg["submodule_gate"]),
             "--json", "--fail-on-change"], cwd=ROOT, check=True)
    upstream = pkg["upstream"]
    workdir = args.workdir or Path(tempfile.mkdtemp(prefix=f"update-{args.package}-"))
    workdir.mkdir(parents=True, exist_ok=True)

    if upstream["type"] == "git-commit":
        commit = args.commit or run.git_head(
            upstream["repo"], upstream["branch"])
        if not re.fullmatch(r"[0-9a-f]{40}", commit):
            raise SystemExit(f"invalid git commit: {commit}")
        digest = git_commit_source(pkg, commit, workdir)
        rendered = render_git_pin(pkg, commit, digest)
        pin_path = workdir / f"{pkg['pin_module']}.scm"
        pin_path.write_text(rendered)
        if args.apply:
            (ROOT / pkg["pin"]).write_text(rendered)
        print(json.dumps({"package": args.package, "commit": commit,
                          "version": upstream.get("version_prefix", "") +
                          commit[:upstream.get("version_length", 7)],
                          "sha256": digest, "pin": str(pin_path),
                          "applied": args.apply}, indent=2, sort_keys=True))
        if args.verify:
            if not args.apply:
                raise SystemExit("--verify requires --apply")
            expr = f"(@ (under-sea packages {pkg['module']}) {pkg['package']})"
            subprocess.run(["guix", "time-machine", "-C", "channels.scm",
                            "--", "build", "-L", "modules",
                            "--no-substitutes", "-e", expr], cwd=ROOT,
                           check=True)
        return 0
    elif upstream["type"] == "github":
        version = args.version or run.detect_package(args.package, pkg)["latest"]
        if not version:
            raise SystemExit("cannot determine a version")
        tag = args.tag or pkg["tag_template"].format(version=version)
        url = (f"https://codeload.github.com/{upstream['repo']}/tar.gz/"
               f"refs/tags/{tag}")
        file_name = f"{pkg['package']}-{version}.tar.gz"
    else:
        version, url = pypi_sdist(upstream["project"])
        if args.version and args.version != version:
            raise SystemExit(
                f"pypi latest is {version}, not requested {args.version}")
        file_name = url.rsplit("/", 1)[-1]

    tarball = fetch(url, workdir / file_name)
    digest = guix_hash(tarball, pkg["hash_format"])
    rendered = render_pin(pkg, version, url, file_name, digest)
    pin_path = workdir / f"{pkg['pin_module']}.scm"
    pin_path.write_text(rendered)
    if args.apply:
        target = ROOT / pkg["pin"]
        target.write_text(rendered)
    result = {
        "package": args.package,
        "version": version,
        "url": url,
        "file_name": file_name,
        "sha256": digest,
        "pin": str(pin_path),
        "applied": args.apply,
    }
    print(json.dumps(result, indent=2, sort_keys=True))
    if args.verify:
        if not args.apply:
            raise SystemExit("--verify requires --apply")
        expr = f"(@ (under-sea packages {pkg['module']}) {pkg['package']})"
        subprocess.run(
            ["guix", "time-machine", "-C", "channels.scm", "--", "build",
             "-L", "modules", "--no-substitutes", "-e", expr],
            cwd=ROOT, check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
