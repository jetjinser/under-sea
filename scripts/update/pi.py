#!/usr/bin/env python3
"""Prepare a pi source release pin and regenerate its Node lock."""
import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import npm  # noqa: E402
import prepare  # noqa: E402
import run  # noqa: E402

ROOT = run.ROOT


def asset_url(pkg, tag, asset, version):
    return ("https://github.com/" + pkg["upstream"]["repo"] +
            "/releases/download/" + tag + "/" +
            asset["file"].replace("{version}", version))


def render_pin(pkg, version, rows):
    lines = [
        ";;; Generated by scripts/update/pi.py; do not edit.",
        f"(define-module (under-sea packages {pkg['pin_module']})",
        "  #:use-module (guix packages)",
        "  #:use-module (guix download)",
        "  #:use-module (guix base16)",
        "  #:export (" + pkg["version_symbol"] + " " +
        " ".join(symbol for symbol, _, _, _ in rows) + "))",
        "",
        f"(define-public {pkg['version_symbol']} \"{version}\")",
        "",
    ]
    for symbol, file_name, url, digest in rows:
        lines += [
            f"(define-public {symbol}",
            "  (origin",
            "    (method url-fetch)",
            f'    (uri "{url}")',
            f'    (file-name "{file_name}")',
            "    (sha256",
            f'     (base16-string->bytevector "{digest}"))))',
            "",
        ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--package", required=True)
    ap.add_argument("--version")
    ap.add_argument("--tag")
    ap.add_argument("--workdir", type=Path)
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--manifest", type=Path, default=run.DEFAULT_MANIFEST)
    args = ap.parse_args()
    data = run.load_manifest(args.manifest)
    pkg = data["packages"].get(args.package)
    if not pkg or pkg.get("adapter") != "pi":
        raise SystemExit(f"{args.package} is not configured as a pi package")
    if pkg["autonomy"] not in ("L3", "L4"):
        raise SystemExit(
            f"{args.package}: autonomy {pkg['autonomy']} does not allow lock updates")
    version = args.version or run.detect_package(args.package, pkg)["latest"]
    if not version:
        raise SystemExit("cannot determine a version")
    tag = args.tag or pkg["tag_template"].format(version=version)
    workdir = args.workdir or (Path("/var/tmp/under-sea-update")
                               / f"{args.package}-{version}")
    workdir.mkdir(parents=True, exist_ok=True)
    rows = []
    source = None
    for asset in pkg["upstream"]["assets"]:
        file_name = asset["file"].replace("{version}", version)
        url = asset_url(pkg, tag, asset, version)
        path = prepare.fetch(url, workdir / file_name)
        digest = prepare.guix_hash(path, pkg.get("hash_format", "base16"))
        rows.append((asset["symbol"], file_name, url, digest))
        if asset["symbol"] == "%pi-source":
            source = path
    if source is None:
        raise SystemExit("pi manifest has no %pi-source asset")
    pin = render_pin(pkg, version, rows)
    (workdir / "pi-lock.scm").write_text(pin)
    src = npm.extract_source(source, workdir)
    lock = pkg["lock"]
    lock_path = workdir / Path(lock["output"]).name
    subprocess.run([
        sys.executable, str(ROOT / lock["script"]),
        "--version", version, "--source-dir", str(src),
        "--output", str(lock_path), "--tarballs", str(workdir / "tarballs"),
    ], cwd=ROOT, check=True)
    if args.apply:
        (ROOT / pkg["pin"]).write_text(pin)
        (ROOT / lock["output"]).write_text(lock_path.read_text())
    print(json.dumps({
        "package": args.package, "version": version, "tag": tag,
        "assets": len(rows), "pin": str(workdir / "pi-lock.scm"),
        "lock": str(lock_path), "applied": args.apply,
    }, indent=2, sort_keys=True))
    if args.verify:
        if not args.apply:
            raise SystemExit("--verify requires --apply")
        expr = f"(@ (under-sea packages {pkg['module']}) {pkg['package']})"
        subprocess.run(
            ["guix", "time-machine", "-C", "channels.scm", "--", "build",
             "-L", "modules", "--no-substitutes", "-e", expr],
            cwd=ROOT, check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
