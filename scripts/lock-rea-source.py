#!/usr/bin/env python3
"""Emit fixed-origin npm tarballs for the REA source build closure.

The published npm tarball already contains dist/, but REA's source build needs
the full package-lock dev/optional closure to run `npm run build` (turbo +
TypeScript).  This script reads package-lock.json from a source checkout and
records every resolved npm tarball as a fixed sha256 origin.  The build then
extracts those origins into node_modules and runs npm offline.

Usage:
  scripts/lock-rea-source.py --version 6.7.0 \
      --source-dir /path/to/rea-rea-agents-6.7.0 \
      --output modules/under-sea/packages/rea-source-lock.scm
"""
import argparse
import concurrent.futures
import hashlib
import json
import os
import tarfile
import tempfile
import urllib.request
from pathlib import Path

REGISTRY = os.environ.get("REA_NPM_REGISTRY", "https://registry.npmjs.org")


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(url, dest):
    if dest.is_file():
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    last = None
    for _ in range(4):
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                tmp.write_bytes(response.read())
            tmp.rename(dest)
            return
        except Exception as exc:  # noqa: BLE001
            last = exc
    raise last


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--version", required=True)
    ap.add_argument("--source-dir", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--tarballs", type=Path, default=None,
                    help="tarball cache (default: a temporary directory)")
    ap.add_argument("--jobs", type=int, default=8)
    args = ap.parse_args()

    source_url = (
        "https://codeload.github.com/morluto/rea/tar.gz/"
        f"refs/tags/rea-agents-{args.version}")
    tarballs = args.tarballs or Path(tempfile.mkdtemp(prefix="rea-source-lock-"))
    tarballs.mkdir(parents=True, exist_ok=True)
    source_tgz = tarballs / "rea-source.tgz"
    fetch(source_url, source_tgz)
    source_sha = sha256_file(source_tgz)

    lock = json.loads((args.source_dir / "package-lock.json").read_text())
    packages = lock["packages"]
    runtime = {
        path: data for path, data in packages.items()
        if path and data.get("resolved")
        and not data.get("link")
        and not str(data["resolved"]).startswith("file:")
    }

    results = {}

    def work(item):
        path, data = item
        url = data["resolved"]
        tgz = tarballs / (hashlib.sha256(url.encode()).hexdigest()[:16] + ".tgz")
        try:
            fetch(url, tgz)
        except Exception as exc:  # noqa: BLE001
            return path, url, None, str(exc)
        return path, url, sha256_file(tgz), None

    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as ex:
        for path, url, digest, err in ex.map(work, sorted(runtime.items())):
            if err:
                raise SystemExit(f"FAIL {path}: {url}: {err}")
            results[path] = (runtime[path].get("version") or "0.0.0",
                             url, digest)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w") as f:
        f.write(";;; Generated by scripts/lock-rea-source.py; do not edit.\n")
        f.write("(define-module (under-sea packages rea-source-lock)\n")
        f.write("  #:use-module (guix packages)\n")
        f.write("  #:use-module (guix download)\n")
        f.write("  #:use-module (guix base16)\n")
        f.write("  #:export (%rea-source-version %rea-source\n")
        f.write("            %rea-build-origins))\n\n")
        f.write(f'(define-public %rea-source-version "{args.version}")\n\n')
        f.write("(define-public %rea-source\n")
        f.write("  (origin\n")
        f.write("    (method url-fetch)\n")
        f.write(f'    (uri "{source_url}")\n')
        f.write(f'    (file-name "rea-agents-{args.version}-source.tar.gz")\n')
        f.write("    (sha256\n")
        f.write(f'     (base16-string->bytevector "{source_sha}"))))\n\n')
        f.write("(define-public %rea-build-origins\n  (list\n")
        for path, (version, url, digest) in sorted(results.items()):
            name = hashlib.sha256(url.encode()).hexdigest()[:16]
            f.write(f'    (list "{path}" "{version}"\n')
            f.write(f'      (origin (method url-fetch) (uri "{url}")\n')
            f.write(f'        (file-name "{name}.tgz")\n')
            f.write(f'        (sha256 (base16-string->bytevector "{digest}"))))\n')
        f.write("))\n")

    print(f"{len(results)} build tarballs pinned", file=os.sys.stderr)


if __name__ == "__main__":
    main()
