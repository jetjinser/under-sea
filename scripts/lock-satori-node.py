"""Generate fixed Guix registry origins for Satori's audited source closure."""
import argparse
import hashlib
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('audit', type=Path)
parser.add_argument('output', type=Path)
parser.add_argument('--import-script', type=Path,
                    help='Optionally emit a Guix script to import hash-verified cached archives')
parser.add_argument('--module', default='hermes-satori-node-lock')
parser.add_argument('--symbol', default='%satori-node-source-origins')
parser.add_argument('--prefix', default='satori-node')
parser.add_argument('--provider', action='append', default=[])
args = parser.parse_args()
data = json.loads(args.audit.read_text())
if not re.fullmatch('[a-z0-9-]+', args.module) or not re.fullmatch('%[a-z0-9-]+', args.symbol) or not re.fullmatch('[a-z0-9-]+', args.prefix):
    raise ValueError('Invalid generated Scheme identifiers')
replaced = {'@esbuild/linux-x64@0.18.10', 'yoga-wasm-web@0.3.3',
            'source-map@0.7.4', 'source-map@0.8.0-beta.0'}
replaced.update(args.provider)
lines = [';;; Generated by scripts/lock-satori-node.py; no install scripts executed.',
         f'(define-module (under-sea packages {args.module})',
         '  #:use-module (guix packages)', '  #:use-module (guix download)',
         '  #:use-module (guix base16))',
         f'(define-public {args.symbol}', '  (list']
identities = set()
imports = []
def supported(values, target):
    positive = [value for value in values if not value.startswith('!')]
    return '!' + target not in values and (not positive or target in positive)

for record in sorted(data['archives'], key=lambda item: item['identity']):
    identity = record['identity']
    if 'sha256' not in record or identity in replaced or 'linuxmusl' in identity or '-musl@' in identity:
        continue
    if any(not supported(record.get(key, []), target) for key, target in
           [('os', 'linux'), ('cpu', 'x64'), ('libc', 'glibc')]):
        continue
    if identity in identities:
        raise ValueError('Duplicate source identity: ' + identity)
    identities.add(identity)
    if args.import_script:
        cached = Path(record['archive'])
        if cached.is_symlink() or not cached.is_file() or hashlib.sha256(cached.read_bytes()).hexdigest() != record['sha256']:
            raise ValueError('Source cache integrity mismatch: ' + identity)
        imports.append('(list ' + ' '.join(json.dumps(value) for value in (
            args.prefix + '-' + record['sha256'][:20] + '.tgz',
            str(cached.resolve()), record['sha256'])) + ')')
    for field in ('identity', 'url', 'sha256'):
        if any(char in record[field] for char in ('"', '\\', '\n', '\r')):
            raise ValueError('Invalid Scheme source field')
    lines.extend([
        f'    (list "{identity}"',
        f'      (origin (method url-fetch) (uri "{record["url"]}")',
        f'        (file-name "{args.prefix}-{record["sha256"][:20]}.tgz")',
        f'        (sha256 (base16-string->bytevector "{record["sha256"]}"))))'])
lines.append('  ))')
args.output.write_text('\n'.join(lines) + '\n')
if args.import_script:
    args.import_script.write_text('''(use-modules (guix store) (guix hash) (guix base16))
(with-store store
 (for-each
  (lambda (entry)
   (unless (string=? (caddr entry)
                    (bytevector->base16-string (file-hash* (cadr entry) #:recursive? #f)))
    (error "Source cache hash changed" (car entry)))
   (format #t "~a\\t~a~%" (car entry)
           (add-to-store store (car entry) #f "sha256" (cadr entry))))
  (list
''' + '\n'.join(imports) + '\n)))\n')
print('Generated', len(identities), 'fixed source origins; full source providers separate')
