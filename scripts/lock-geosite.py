#!/usr/bin/env python3
"""Lock official geosite/GeoIP generators and their consumed Go modules."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import runpy
import shutil
import subprocess
import tarfile
import tempfile

helpers = runpy.run_path(str(Path(__file__).with_name('lock-sing-box.py')))
origin, scheme = helpers['origin'], helpers['scheme']
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('commit')
parser.add_argument('archive', type=Path)
parser.add_argument('source', type=Path)
parser.add_argument('--project', choices=('geosite', 'geoip'), default='geosite')
parser.add_argument('--cache', type=Path)
parser.add_argument('--output', type=Path)
args = parser.parse_args()
project = args.project
repository = 'domain-list-community' if project == 'geosite' else 'geoip'
args.cache = args.cache or Path('/tmp/under-sea-' + project + '-lock')
args.output = args.output or Path('under-sea/packages/' + project + '-lock.scm')
if len(args.commit) != 40 or any(c not in '0123456789abcdef' for c in args.commit):
    parser.error('A full official source commit is required')
source, cache = args.source.resolve(), args.cache.resolve()
metadata = {name: (source / name).read_bytes() for name in ('go.mod', 'go.sum')}
with tarfile.open(args.archive) as archive:
    for name, content in metadata.items():
        member = archive.extractfile(repository + '-' + args.commit + '/' + name)
        if member is None or member.read() != content:
            raise ValueError('Source/archive identity mismatch: ' + name)
cache.mkdir(parents=True, exist_ok=True)
identity = json.dumps([args.commit, hashlib.sha256(args.archive.read_bytes()).hexdigest()])
state = cache / 'source-identity.json'
if state.exists() and state.read_text() != identity:
    raise ValueError('Use a fresh cache for a different geosite source')
if not state.exists() and (cache / 'modules').exists():
    raise ValueError('Unidentified module cache')
state.write_text(identity)
env = dict(os.environ, GOTOOLCHAIN='local', GOENV='off', GOWORK='off',
           GOFLAGS='', GOOS='linux', GOARCH='amd64', CGO_ENABLED='0',
           GOSUMDB='sum.golang.org', GOPROXY='https://proxy.golang.org',
           GOPATH=str(cache / 'gopath'), GOMODCACHE=str(cache / 'modules'),
           GOCACHE=str(cache / 'build'))
data = subprocess.check_output(['go', 'list', '-mod=readonly', '-buildvcs=false',
                                '-deps', '-json', '.'], cwd=source, env=env, text=True)
selected, position, decoder = set(), 0, json.JSONDecoder()
while position < len(data):
    if data[position].isspace():
        position += 1
        continue
    package, position = decoder.raw_decode(data, position)
    module = package.get('Module', {})
    module = module.get('Replace', module)
    if 'Version' in module:
        escaped = ''.join('!' + c.lower() if c.isupper() else c for c in module['Path'])
        selected.add(escaped + '/@v/' + module['Version'])
for name, content in metadata.items():
    if (source / name).read_bytes() != content:
        raise ValueError('Go modified locked metadata: ' + name)
proxy, inputs = cache / 'modules/cache/download', cache / 'inputs'
inputs.mkdir(exist_ok=True)
lines = [';;; Generated by scripts/lock-geosite.py.',
         '(define-module (under-sea packages ' + project + '-lock)',
         '  #:use-module (guix packages) #:use-module (guix download)',
         '  #:use-module (guix base16))',
         '(define-public %' + project + '-source ' + origin(
             'https://codeload.github.com/v2fly/' + repository + '/tar.gz/' + args.commit,
             project + '-' + args.commit + '.tar.gz', args.archive) + ')',
         '(define-public %' + project + '-module-files (list']
for path in sorted(proxy.rglob('*')):
    if not path.is_file():
        continue
    relative = path.relative_to(proxy).as_posix()
    if path.suffix != '.mod' and not (path.suffix in ('.zip', '.info') and
                                    relative.rsplit('.', 1)[0] in selected):
        continue
    name = 'go-source-' + hashlib.sha256(relative.encode()).hexdigest()[:20] + path.suffix
    locked = inputs / name
    if path.suffix == '.info':
        # Go rewrites JSON field order in its module cache. Guix hashes the
        # proxy's raw response, so preserve those bytes after checking that
        # every semantic metadata field matches the checksum-verified cache.
        raw = subprocess.check_output(['curl', '-fsSL', '--retry', '2',
                                       'https://proxy.golang.org/' + relative])
        if json.loads(raw) != json.loads(path.read_bytes()):
            raise ValueError('Proxy/cache module metadata differs: ' + relative)
        locked.write_bytes(raw)
    else:
        shutil.copyfile(path, locked)
    lines.append('(list ' + scheme(relative) + ' ' +
                 origin('https://proxy.golang.org/' + relative, name, locked) + ')')
lines.append('))\n')
shutil.copyfile(args.archive, inputs / (project + '-' + args.commit + '.tar.gz'))
args.output.parent.mkdir(parents=True, exist_ok=True)
with tempfile.NamedTemporaryFile(mode='w', dir=args.output.parent, delete=False) as target:
    target.write('\n'.join(lines))
    temporary = target.name
os.replace(temporary, args.output)
print('Wrote exact ' + project + ' generator sources: ' + str(args.output))
